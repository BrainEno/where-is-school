#!/usr/bin/env python3
"""Build the classroom backpack's sewn panels and woven canvas from first-party geometry.

Dimensions are metres; +Z is the front. Meshes are split only where a material or the
moving flap needs its own surface. The pocket and top opening have genuine interior
walls; painted dark rectangles would look flat when the flap lifts above them.
"""
from __future__ import annotations

import argparse
import math
from pathlib import Path
import random
import struct
import zlib

ROOT = Path(__file__).resolve().parents[2]
MODELS = ROOT / "assets/models/classroom/schoolbag"
MATERIALS = ROOT / "assets/materials/classroom"
Vec = tuple[float, float, float]


class Panel:
    def __init__(self) -> None:
        self.points: list[Vec] = []
        self.faces: list[tuple[int, ...]] = []

    def loft(self, rings: list[list[Vec]], closed: bool = True) -> None:
        count = len(rings[0])
        start = len(self.points) + 1
        for ring in rings:
            assert len(ring) == count
            self.points.extend(ring)
        for row in range(len(rings) - 1):
            a = start + row * count
            b = a + count
            for i in range(count):
                j = (i + 1) % count
                self.faces.append((a + i, b + i, b + j, a + j))
        if closed:
            end = start + (len(rings) - 1) * count
            self.faces.append(tuple(range(start, start + count)))
            self.faces.append(tuple(range(end + count - 1, end - 1, -1)))

    def obj(self) -> bytes:
        return ("# Generated by art/classroom/build_schoolbag.py; units: metres\n" +
                "\n".join("v %.5f %.5f %.5f" % p for p in self.points) +
                "\ns 1\n" + "\n".join(f"f {face[0]} {face[i]} {face[i+1]}"
                                       for face in self.faces for i in range(1, len(face) - 1)) +
                "\n").encode("ascii")


def soft_rect(y: float, width: float, depth: float, z: float = 0.0, sway: float = 0.0) -> list[Vec]:
    points = []
    for i in range(32):
        t = math.tau * i / 32
        x, u = math.cos(t), math.sin(t)
        x = math.copysign(abs(x) ** 0.55, x)
        u = math.copysign(abs(u) ** 0.59, u)
        crease = 1 + 0.018 * math.sin(7 * t + y * 19) + 0.012 * math.cos(5 * t - y * 11)
        points.append((x * width * crease, y + sway * (0.6 * x + 0.4 * u), z + u * depth * crease))
    return points


def shell() -> Panel:
    panel = Panel()
    panel.loft([soft_rect(*row) for row in (
        (0.010, 0.135, 0.074), (0.027, 0.161, 0.090, 0.003),
        (0.065, 0.174, 0.106, 0.006, -0.003), (0.165, 0.170, 0.110, 0.004, 0.002),
        (0.254, 0.166, 0.104, -0.003, 0.005), (0.319, 0.163, 0.098, -0.004, -0.006),
        (0.357, 0.147, 0.093, -0.005, -0.009), (0.366, 0.138, 0.084, -0.006, -0.010),
        (0.354, 0.132, 0.077, -0.006, -0.009), (0.280, 0.143, 0.083, -0.004, 0.002),
    )], closed=False)
    # Cap the base with a hidden inner floor instead of closing the visible mouth.
    panel.faces.append(tuple(range(1, 33)))
    panel.faces.append(tuple(range(len(panel.points), len(panel.points) - 32, -1)))
    return panel


def pocket() -> Panel:
    panel = Panel()
    panel.loft([soft_rect(*row) for row in (
        (0.061, 0.101, 0.024, 0.094), (0.084, 0.134, 0.035, 0.107, -0.005),
        (0.150, 0.137, 0.037, 0.107, -0.005), (0.213, 0.125, 0.031, 0.109, -0.009),
        (0.231, 0.111, 0.022, 0.110, -0.009), (0.233, 0.107, 0.015, 0.109, -0.009),
        (0.209, 0.105, 0.013, 0.110, -0.009),
    )])
    # A slip pocket on the right is where the fingers sweep last.
    panel.loft([[(z + 0.083, y, -x + 0.009) for x, y, z in soft_rect(*row)] for row in (
        (0.074, 0.056, 0.019, 0.079), (0.101, 0.063, 0.025, 0.082),
        (0.236, 0.062, 0.023, 0.082, 0.008), (0.247, 0.056, 0.016, 0.082, 0.009),
        (0.226, 0.051, 0.012, 0.083, 0.009),
    )])
    return panel


def lid() -> Panel:
    panel = Panel()
    # Cross-sections of the flap walk from the sewn hinge past the brim, then dip
    # asymmetrically down the front like loose canvas, not like a hinged plank.
    rings = []
    for z, y, w, bank in (
        (0.000, -0.010, 0.112, 0.003), (0.027, 0.007, 0.143, 0.003),
        (0.084, 0.016, 0.163, -0.001), (0.156, 0.004, 0.164, -0.004),
        (0.190, -0.026, 0.160, -0.008), (0.207, -0.065, 0.145, -0.009),
        (0.208, -0.100, 0.116, -0.013), (0.202, -0.109, 0.089, -0.013),
    ):
        ring = []
        for i in range(24):
            t = math.tau * i / 24
            x = math.cos(t)
            ring.append((w * x, y - 0.014 * x * x + x * bank - math.sin(t) * 0.005, z))
        rings.append(ring)
    panel.loft(rings)
    return panel


def ribbon(path: list[Vec], width: float, thickness: float) -> Panel:
    panel = Panel()
    rings = []
    for i, (x, y, z) in enumerate(path):
        a = path[max(i - 1, 0)]
        b = path[min(i + 1, len(path) - 1)]
        h = math.hypot(b[1] - a[1], b[2] - a[2])
        dy, dz = -(b[2] - a[2]) / h, (b[1] - a[1]) / h
        w = width * (0.8 if i in (0, len(path) - 1) else 1.0)
        rings.append([(x + w * math.cos(t), y + dy * thickness * math.sin(t),
                       z + dz * thickness * math.sin(t)) for t in (math.tau * k / 12 for k in range(12))])
    panel.loft(rings)
    return panel


def canvas() -> bytes:
    """Subtle over-under threads over indigo dye, with heavier flecks at thread crossings."""
    n = 128
    rng = random.Random(4482)
    chunks = []
    for y in range(n):
        row = bytearray([0])
        for x in range(n):
            yarn = (x // 2 + y // 2) % 2
            grain = (x % 2 if yarn else y % 2) * 8 - 3
            grain += rng.randint(-4, 5) + round(4 * math.cos(math.tau * (x + y * 2) / n))
            row.extend(c + grain for c in (39, 71, 116))
        chunks.append(bytes(row))

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", n, n, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(b"".join(chunks), 9)) + chunk(b"IEND", b""))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    check = parser.parse_args().check
    strap = ribbon([(0.005, 0.342, -0.080), (0.0, 0.358, -0.104),
                    (-0.008, 0.322, -0.138), (-0.009, 0.266, -0.155),
                    (0.005, 0.191, -0.150), (0.013, 0.115, -0.115),
                    (0.022, 0.082, -0.086)], 0.021, 0.006)
    loop = ribbon([(0.0, 0.348, -0.085), (0.0, 0.392, -0.090),
                   (0.0, 0.433, -0.114), (0.0, 0.454, -0.134),
                   (0.0, 0.419, -0.142), (0.0, 0.381, -0.132)], 0.024, 0.006)
    hook = ribbon([(0.0, 0.394, -0.148), (0.0, 0.441, -0.149), (0.0, 0.458, -0.137),
                   (0.0, 0.448, -0.112), (0.0, 0.428, -0.106)], 0.025, 0.005)
    assets = {MODELS / f"{name}.obj": panel.obj() for name, panel in
              [("shell", shell()), ("pocket", pocket()), ("flap", lid()),
               ("strap", strap), ("handle", loop), ("hook", hook)]}
    assets[MATERIALS / "textures" / "canvas_indigo.png"] = canvas()
    mismatched = []
    for path, data in assets.items():
        if check:
            if not path.exists() or path.read_bytes() != data:
                mismatched.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if mismatched:
        print("Schoolbag source differs: " + ", ".join(map(str, mismatched)))
        return 1
    print(f"Schoolbag source: {len(assets)} assets, {sum(len(data) for data in assets.values())} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
