def tile_noise_texture(base, light, dark, seed: int, size: tuple[int, int], streak_dir: str, colors: int) -> Image.Image:
    """A small tileable painted surface (wood, lacquer, canvas). Painted once, then made
    seamless by cross-fading with a copy shifted by half a tile: the shifted copy is the
    one shown at the borders, and its own seam sits in the middle, where the original
    covers it."""
    w, h = size
    c = Canvas(w / 100.0, h / 100.0, 100.0, base, seed=seed)
    rng = c.rng
    strokes_l, strokes_d = [], []
    for _ in range(int(20 * (w * h) / (256 * 256)) + 12):
        s = rng.uniform(0, c.width_m)
        y = rng.uniform(0, c.height_m)
        if streak_dir == "h":
            pts = [(s, y), (s + rng.uniform(0.6, 1.6), y + rng.uniform(-0.03, 0.03))]
        elif streak_dir == "v":
            pts = [(s, y), (s + rng.uniform(-0.03, 0.03), y + rng.uniform(0.6, 1.6))]
        else:
            ang = rng.uniform(0, math.pi)
            pts = [(s, y), (s + math.cos(ang) * 0.5, y + math.sin(ang) * 0.5)]
        (strokes_l if rng.random() < 0.5 else strokes_d).append((pts, rng.uniform(0.05, 0.16), {"bristles": 8, "dryness": 0.5, "wobble_m": 0.01}))
    c.brush(jitter(light, rng, 0.02), strokes_l, opacity=0.55)
    c.brush(jitter(dark, rng, 0.02), strokes_d, opacity=0.5)
    shifted = np.roll(np.roll(c.rgb, h // 2, axis=0), w // 2, axis=1)
    ux = np.abs(np.linspace(-1.0, 1.0, w, dtype=np.float32))
    uy = np.abs(np.linspace(-1.0, 1.0, h, dtype=np.float32))
    edge = np.maximum(ux[None, :], uy[:, None])
    keep = smoothstep(0.95, 0.55, edge)[..., None]
    c.rgb = c.rgb * keep + shifted * (1.0 - keep)
    return c.image(colors)


