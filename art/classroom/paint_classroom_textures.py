def scribble_word(c: Canvas, s: float, y: float, length: float, height: float, width_m: float, opacity: float, color=CHALK) -> None:
    """Illegible chalk 'writing': loops and verticals that read as a word, not as text."""
    x = s
    while x < s + length:
        kind = c.rng.integers(0, 3)
        w = height * c.rng.uniform(0.35, 0.8)
        if kind == 0:
            c.chalk([(x, y), (x + w * 0.5, y + height), (x + w, y)], width_m, color, opacity)
        elif kind == 1:
            c.chalk([(x, y + height), (x, y), (x + w, y + height * 0.5)], width_m, color, opacity)
        else:
            c.chalk([(x, y + height * 0.5), (x + w * 0.5, y + height), (x + w, y + height * 0.4), (x + w * 0.6, y)], width_m, color, opacity)
        x += w * c.rng.uniform(0.9, 1.3)


