#!/usr/bin/env python3
"""Paints the classroom's hand-made textures.

    python3 art/classroom/paint_classroom_textures.py

Writes every PNG under `assets/materials/classroom/textures/` together with its Godot
`.import` sidecar. Nothing here is downloaded, traced or generated by a model: every mark
is a brush, plane or line placed by the code below from a fixed seed, so the same command
on the same Pillow/NumPy versions repaints the same files (see README.md next to this file
for the versions and the colour system).

The painting vocabulary is deliberately small:

- **planes** - flat colour areas whose edges are roughened with noise instead of ruled;
- **dry brush** - bundles of thin bristle lines that thin out and break towards the end
  of a stroke, so a surface carries visible direction rather than noise;
- **ink** - a warm black line with a wobble and a varying width, used for contours,
  corners and the few graffiti-like marks;
- **chalk** - broken, low-contrast pale marks for the boards.

Every image is posterized to a small palette at the end. That is what keeps the walls
reading as colour planes from the game camera, and it keeps each file small enough for
the build's texture budget (tools/verify_build.py).

Coordinates: each wall is painted in *viewer space* - metres from the left edge as seen
from inside the room, and metres up from the floor - so the numbers below can be checked
against `classroom.tscn` directly (see `wall_s` / the comments at each wall).
"""

