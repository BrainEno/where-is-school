# --- small numeric toolkit ------------------------------------------------------------


def rgb(color: tuple[int, int, int]) -> np.ndarray:
    return np.array(color, np.float32) / 255.0


def jitter(color: tuple[int, int, int], rng: np.random.Generator, amount: float) -> np.ndarray:
    """A colour nudged in value and very slightly in hue: one brushload."""
    base = rgb(color)
    value = 1.0 + rng.uniform(-amount, amount)
    tint = rng.uniform(-amount * 0.35, amount * 0.35, 3)
    return np.clip(base * value + tint, 0.0, 1.0)


def smoothstep(e0: float, e1: float, x: np.ndarray) -> np.ndarray:
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def value_noise(w: int, h: int, cell: float, rng: np.random.Generator, octaves: int = 3) -> np.ndarray:
    """Smooth noise in 0..1 from upsampled random grids."""
    out = np.zeros((h, w), np.float32)
    amp, total = 1.0, 0.0
    for _ in range(octaves):
        gw = max(2, int(w / cell) + 2)
        gh = max(2, int(h / cell) + 2)
        grid = (rng.random((gh, gw)) * 255).astype(np.uint8)
        layer = Image.fromarray(grid).resize((w, h), Image.BICUBIC)
        out += np.asarray(layer, np.float32) / 255.0 * amp
        total += amp
        amp *= 0.5
        cell = max(2.0, cell / 2.0)
    return out / total


class Canvas:
    """An RGBA float canvas with a metric coordinate system."""

    def __init__(self, width_m: float, height_m: float, ppm: float, color, seed: int, alpha: float = 1.0):
        self.ppm = ppm
        self.width_m = width_m
        self.height_m = height_m
        self.w = max(8, int(round(width_m * ppm)))
        self.h = max(8, int(round(height_m * ppm)))
        self.rng = np.random.default_rng(seed)
        self.rgb = np.ones((self.h, self.w, 3), np.float32) * rgb(color)
        self.a = np.full((self.h, self.w), alpha, np.float32)

    # metres (viewer space, y up from the bottom edge) -> pixels (y down)
    def px(self, s: float, y: float) -> tuple[float, float]:
        return s * self.ppm, (self.height_m - y) * self.ppm

    def m(self, metres: float) -> float:
        return metres * self.ppm

    def blank_mask(self) -> tuple[Image.Image, ImageDraw.ImageDraw]:
        mask = Image.new("L", (self.w, self.h), 0)
        return mask, ImageDraw.Draw(mask)

    def paint(self, color, mask: np.ndarray, opacity: float = 1.0) -> None:
        """Lays `color` over the canvas through `mask` (0..1)."""
        a = np.clip(mask * opacity, 0.0, 1.0)[..., None]
        col = color if isinstance(color, np.ndarray) else rgb(color)
        self.rgb = self.rgb * (1.0 - a) + col * a
        self.a = np.maximum(self.a, a[..., 0])

    def paint_alpha(self, color, mask: np.ndarray, opacity: float = 1.0) -> None:
        """Like `paint`, but composites alpha properly for a transparent canvas."""
        a = np.clip(mask * opacity, 0.0, 1.0)
        col = color if isinstance(color, np.ndarray) else rgb(color)
        out_a = a + self.a * (1.0 - a)
        safe = np.where(out_a > 1e-5, out_a, 1.0)
        self.rgb = (col * a[..., None] + self.rgb * (self.a * (1.0 - a))[..., None]) / safe[..., None]
        self.a = out_a

    def shade(self, factor: np.ndarray) -> None:
        self.rgb = np.clip(self.rgb * factor[..., None], 0.0, 1.0)

    # --- shapes ----------------------------------------------------------------------

    def polygon_mask(self, points_m, rough: float = 0.35, cell_m: float = 0.06, blur_m: float = 0.012) -> np.ndarray:
        """A filled polygon whose edge has been roughened rather than ruled."""
        mask, draw = self.blank_mask()
        draw.polygon([self.px(s, y) for s, y in points_m], fill=255)
        return self.roughen(mask, rough, cell_m, blur_m)

    def rect_mask(self, s0, y0, s1, y1, **kw) -> np.ndarray:
        return self.polygon_mask([(s0, y0), (s1, y0), (s1, y1), (s0, y1)], **kw)

    def roughen(self, mask: Image.Image, rough: float, cell_m: float, blur_m: float) -> np.ndarray:
        blur = max(0.6, self.m(blur_m))
        soft = np.asarray(mask.filter(ImageFilter.GaussianBlur(blur)), np.float32) / 255.0
        if rough <= 0.0:
            return smoothstep(0.35, 0.65, soft)
        noise = value_noise(self.w, self.h, max(2.0, self.m(cell_m)), self.rng, 3)
        return smoothstep(0.42, 0.58, soft + (noise - 0.5) * rough)

    # --- brush -----------------------------------------------------------------------

    def path(self, points_m, steps: int = 24, wobble_m: float = 0.0) -> list[tuple[float, float]]:
        """A smooth path through the given points (pixels), with optional hand wobble."""
        pts = [self.px(s, y) for s, y in points_m]
        if len(pts) == 1:
            return pts
        out: list[tuple[float, float]] = []
        total = len(pts) - 1
        phase = self.rng.uniform(0, math.tau)
        freq = self.rng.uniform(1.5, 3.5)
        wob = self.m(wobble_m)
        for i in range(total):
            (x0, y0), (x1, y1) = pts[i], pts[i + 1]
            for k in range(steps):
                t = k / steps
                x = x0 + (x1 - x0) * t
                y = y0 + (y1 - y0) * t
                if wob > 0.0:
                    g = (i + t) / total
                    dx, dy = x1 - x0, y1 - y0
                    length = math.hypot(dx, dy) or 1.0
                    nx, ny = -dy / length, dx / length
                    off = wob * (math.sin(g * math.tau * freq + phase) * 0.7 + self.rng.normal(0, 0.12))
                    x += nx * off
                    y += ny * off
                out.append((x, y))
        out.append(pts[-1])
        return out

    def stroke_mask(
        self,
        points_m,
        width_m: float,
        bristles: int = 14,
        dryness: float = 0.35,
        wobble_m: float = 0.01,
        mask: Image.Image | None = None,
    ) -> Image.Image:
        """A dry-brush stroke: parallel bristles that fade and break towards the end."""
        if mask is None:
            mask = Image.new("L", (self.w, self.h), 0)
        layer = Image.new("L", (self.w, self.h), 0)
        draw = ImageDraw.Draw(layer)
        path = self.path(points_m, steps=18, wobble_m=wobble_m)
        width = self.m(width_m)
        bristle_w = max(1, int(round(width / bristles * 1.7)))
        n = len(path)
        for b in range(bristles):
            offset = (b / max(1, bristles - 1) - 0.5) * width + self.rng.normal(0, width * 0.03)
            ink = self.rng.uniform(0.45, 1.0)
            # Where this bristle runs out of paint, as a fraction of the stroke.
            runs_out = 1.0 - dryness * self.rng.random() ** 0.7
            prev = None
            for i in range(n):
                t = i / max(1, n - 1)
                if t > runs_out:
                    break
                x, y = path[i]
                j = min(n - 1, i + 1)
                dx, dy = path[j][0] - x, path[j][1] - y
                if i == n - 1:
                    dx, dy = x - path[i - 1][0], y - path[i - 1][1]
                length = math.hypot(dx, dy) or 1.0
                nx, ny = -dy / length, dx / length
                point = (x + nx * offset, y + ny * offset)
                # Dry brush breaks up near its end.
                if prev is not None and self.rng.random() > dryness * t * 0.9:
                    fade = 1.0 - max(0.0, t - runs_out + 0.25) * 1.6
                    value = int(255 * ink * max(0.25, min(1.0, fade)))
                    draw.line([prev, point], fill=value, width=bristle_w)
                prev = point
        return ImageChops.lighter(mask, layer)

    def brush(self, color, strokes, opacity: float = 1.0, soften_m: float = 0.0) -> None:
        """Paints a batch of strokes in one colour. `strokes` = [(points_m, width_m, kw)]."""
        mask = Image.new("L", (self.w, self.h), 0)
        for points, width, kw in strokes:
            mask = self.stroke_mask(points, width, mask=mask, **kw)
        if soften_m > 0.0:
            mask = mask.filter(ImageFilter.GaussianBlur(self.m(soften_m)))
        self.paint(color, np.asarray(mask, np.float32) / 255.0, opacity)

    def ink_line(
        self,
        points_m,
        width_m: float = 0.012,
        wobble_m: float = 0.006,
        color=INK,
        opacity: float = 1.0,
        taper: bool = True,
        broken: float = 0.0,
        alpha_canvas: bool = False,
    ) -> None:
        """A hand-drawn line: wobbling, swelling and thinning, sometimes lifting off."""
        mask = Image.new("L", (self.w, self.h), 0)
        draw = ImageDraw.Draw(mask)
        path = self.path(points_m, steps=40, wobble_m=wobble_m)
        width = self.m(width_m)
        n = len(path)
        swell_phase = self.rng.uniform(0, math.tau)
        for i in range(n - 1):
            t = i / max(1, n - 1)
            if broken > 0.0 and self.rng.random() < broken * 0.08:
                continue
            w = width * (0.75 + 0.35 * math.sin(t * 9.0 + swell_phase))
            if taper:
                w *= min(1.0, 0.35 + t * 6.0, 0.35 + (1.0 - t) * 6.0)
            draw.line([path[i], path[i + 1]], fill=255, width=max(1, int(round(w))))
        m = np.asarray(mask.filter(ImageFilter.GaussianBlur(0.6)), np.float32) / 255.0
        if alpha_canvas:
            self.paint_alpha(color, m, opacity)
        else:
            self.paint(color, m, opacity)

    def chalk(self, points_m, width_m: float, color=CHALK, opacity: float = 0.6, wobble_m: float = 0.004) -> None:
        """A chalk mark: grainy, broken, never solid."""
        mask = Image.new("L", (self.w, self.h), 0)
        mask = self.stroke_mask(points_m, width_m, bristles=5, dryness=0.55, wobble_m=wobble_m, mask=mask)
        m = np.asarray(mask, np.float32) / 255.0
        grain = self.rng.random((self.h, self.w)).astype(np.float32)
        self.paint(color, m * (grain > 0.35), opacity)

    def mottle(self, color, cell_m: float, amount: float, lo: float = 0.45, hi: float = 0.75) -> None:
        """Broad, soft variation inside a plane - the unevenness of hand-mixed paint."""
        noise = value_noise(self.w, self.h, self.m(cell_m), self.rng, 2)
        self.paint(color, smoothstep(lo, hi, noise), amount)

    # --- output ----------------------------------------------------------------------

    def image(self, colors: int, alpha: str = "opaque") -> Image.Image:
        """Posterizes to `colors` and returns a PIL image.

        alpha: "opaque" (RGB), "cut" (RGBA, alpha snapped to 0/255 for alpha scissor),
        "blend" (RGBA, alpha quantized to 16 levels for alpha blending)."""
        img = Image.fromarray((np.clip(self.rgb, 0, 1) * 255 + 0.5).astype(np.uint8))
        img = img.quantize(colors=colors, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE).convert("RGB")
        if alpha == "opaque":
            return img
        a = np.clip(self.a, 0, 1)
        if alpha == "cut":
            a8 = np.where(a > 0.5, 255, 0).astype(np.uint8)
        else:
            a8 = (np.round(a * 15) * 17).astype(np.uint8)
        out = img.convert("RGBA")
        out.putalpha(Image.fromarray(a8))
        return out


# --- shared wall vocabulary -----------------------------------------------------------

DADO_TOP = 1.05  # metres; the painted wainscot band, the classroom's horizon line


def paint_wall(c: Canvas, openings: list[tuple[float, float, float, float]] | None = None) -> None:
    """The plaster above, the wainscot below, the ink at the seam and in the corners."""
    rng = c.rng
    # Plaster: broad vertical brush planes in three close ivories.
    strokes = []
    s = -0.2
    while s < c.width_m + 0.2:
        width = rng.uniform(0.28, 0.55)
        lean = rng.uniform(-0.12, 0.12)
        strokes.append(([(s, c.height_m + 0.1), (s + lean, DADO_TOP - 0.05)], width, {"bristles": 16, "dryness": 0.5, "wobble_m": 0.02}))
        s += width * rng.uniform(0.55, 0.9)
    for shade, subset in ((IVORY_LIGHT, strokes[0::3]), (IVORY_SHADE, strokes[1::4])):
        c.brush(jitter(shade, rng, 0.02), subset, opacity=0.55)
    c.mottle(rgb(IVORY_SHADE), 0.9, 0.35)
    # A painted (not lit) shadow band under the ceiling: a stage flat, not a render.
    top = c.rect_mask(-0.1, c.height_m - 0.32, c.width_m + 0.1, c.height_m + 0.1, rough=0.45, cell_m=0.08)
    c.paint(rgb(IVORY_SHADE) * 0.93, top, 0.75)

    # The wainscot: a teal band whose top edge is brushed, not ruled.
    dado = c.polygon_mask(
        [(-0.1, -0.1), (c.width_m + 0.1, -0.1), (c.width_m + 0.1, DADO_TOP), (-0.1, DADO_TOP)],
        rough=0.55,
        cell_m=0.035,
        blur_m=0.01,
    )
    c.paint(TEAL, dado)
    bands = []
    s = -0.3
    while s < c.width_m + 0.3:
        length = rng.uniform(0.9, 1.8)
        y = rng.uniform(0.15, DADO_TOP - 0.12)
        bands.append(([(s, y), (s + length, y + rng.uniform(-0.04, 0.04))], rng.uniform(0.12, 0.26), {"bristles": 12, "dryness": 0.55, "wobble_m": 0.01}))
        s += length * rng.uniform(0.35, 0.7)
    c.brush(jitter(TEAL_LIGHT, rng, 0.03), bands[0::2], opacity=0.45 * 1.0)
    c.brush(jitter(TEAL_DARK, rng, 0.03), bands[1::3], opacity=0.5)
    # The seam between the two paints, in ink, slightly drunk.
    seam = []
    s = -0.05
    while s < c.width_m + 0.05:
        seam.append((s, DADO_TOP + rng.uniform(-0.012, 0.012)))
        s += rng.uniform(0.4, 0.9)
    seam.append((c.width_m + 0.05, DADO_TOP))
    c.ink_line(seam, width_m=0.016, wobble_m=0.006, taper=False, broken=0.25)
    # The corners of the room, drawn rather than modelled.
    for edge in (0.025, c.width_m - 0.025):
        c.ink_line([(edge, -0.05), (edge + rng.uniform(-0.02, 0.02), c.height_m + 0.05)], width_m=0.022, wobble_m=0.008, taper=False)
    # Whatever is cut out of the wall (a door) is cut out of the paint too.
    for s0, y0, s1, y1 in openings or []:
        mask, draw = c.blank_mask()
        x0, py1 = c.px(s0, y0)
        x1, py0 = c.px(s1, y1)
        draw.rectangle([x0, py0, x1, py1], fill=255)
        c.a = np.where(np.asarray(mask) > 0, 0.0, c.a)


def tally(c: Canvas, s: float, y: float, groups: int, size: float = 0.07) -> None:
    """Chalk tally marks, the oldest graffiti there is."""
    for g in range(groups):
        x = s + g * size * 1.25
        for k in range(4):
            xx = x + k * size * 0.2
            c.chalk([(xx, y), (xx + c.rng.uniform(-0.006, 0.006), y + size)], 0.01, opacity=0.55)
        c.chalk([(x - size * 0.1, y + size * 0.15), (x + size * 0.8, y + size * 0.85)], 0.01, opacity=0.55)


