#!/usr/bin/env python3
"""Paints the street's ditch and the bare earth along it.

    python3 scenes/environment/props/stage_art/source/paint_street_ditch.py

The owner's reference for this pass is a collage: a grainy, near-monochrome print of a
chalk shore cut by long dark runnels, with one pale yellow ribbed panel pasted upright
into it. Real ground, printed slightly wrong. So these textures are not brushed like the
rest of the stage pass (`paint_stage_textures.py`); they are built from noise as a
photograph would be, then printed: mapped onto one mauve-grey ramp and dithered onto a
small palette, which is where the grain comes from.

Every file tiles along the ditch (world z). Noise is filtered in the frequency domain, so
it wraps by construction; nothing is downloaded, traced, photographed or generated by an
image model. Fixed seeds 3151-3154: the same command on the same NumPy/Pillow versions
repaints the same files. Each PNG is written with its Godot `.import` sidecar.

Sizes and orientations are kept in step with `build_stage_art.py`, which places them:

* `street_earth.png`  - plan view, 4.8 x 9.6 m, column 0 on the ditch's bank (world
  x -9.1), top row towards world -Z. Alpha cut: the east edge crumbles into the asphalt.
* `ditch_water.png`   - plan view, 0.625 x 9.6 m, column 0 against the kerb (world triplanar,
  so the bands land on the walls). The water is unshaded: a strip of sky lying in the street.
* `ditch_wall.png`    - the lining under the kerb, 2.48 x 0.62 m as seen from the road, the
  waterline 0.38 m down (where `Gutter` floats).
* `ditch_grate.png`   - a 0.2 m tile of cast-iron slots, for the drain cover.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
sys.path.insert(0, str(ROOT / "art" / "classroom"))

from paint_classroom_textures import import_sidecar  # noqa: E402

OUT_DIR = HERE.parent / "textures"
RES_DIR = "res://scenes/environment/props/stage_art/textures"

# The print's one ramp: wet black-mauve, raw earth, chalk. Every texture of the pass is
# mapped onto it, so the ditch, the bank and the road edge come out of one plate.
RAMP = [
    (0.00, (30, 26, 32)),
    (0.22, (66, 58, 64)),
    (0.45, (112, 100, 100)),
    (0.68, (160, 148, 140)),
    (0.86, (204, 196, 186)),
    (1.00, (236, 232, 224)),
]

EARTH_M = (4.8, 9.6)
EARTH_PX_M = 80.0
WATER_M = (0.625, 9.6)
WATER_PX_M = 160.0
WALL_M = (2.48, 0.62)
WALL_PX_M = 206.0
WATERLINE_M = 0.38


# --- noise ----------------------------------------------------------------------------------


def wrap_noise(h: int, w: int, rng: np.random.Generator, sy: float, sx: float | None = None) -> np.ndarray:
    """Gaussian-filtered white noise that wraps on both axes; zero mean, unit deviation.
    `sy`/`sx` are the filter's widths in pixels (anisotropic when they differ)."""
    sx = sy if sx is None else sx
    white = rng.standard_normal((h, w))
    fy = np.fft.fftfreq(h)[:, None]
    fx = np.fft.fftfreq(w)[None, :]
    gain = np.exp(-2.0 * np.pi ** 2 * ((fy * sy) ** 2 + (fx * sx) ** 2))
    out = np.real(np.fft.ifft2(np.fft.fft2(white) * gain))
    out -= out.mean()
    return out / (out.std() + 1e-9)


def fbm(h: int, w: int, rng: np.random.Generator, sigma: float, octaves: int = 4, sx: float | None = None) -> np.ndarray:
    out = np.zeros((h, w))
    amp, total = 1.0, 0.0
    sx = sigma if sx is None else sx
    for _ in range(octaves):
        out += amp * wrap_noise(h, w, rng, max(0.6, sigma), max(0.6, sx))
        total += amp
        amp *= 0.55
        sigma, sx = sigma / 2.0, sx / 2.0
    return out / total


def smooth(e0: float, e1: float, x: np.ndarray) -> np.ndarray:
    t = np.clip((x - e0) / (e1 - e0), 0.0, 1.0)
    return t * t * (3.0 - 2.0 * t)


def wrap_dist(a: np.ndarray, b: float, period: float) -> np.ndarray:
    d = np.abs(a - b) % period
    return np.minimum(d, period - d)


def cells(h: int, w: int, rng: np.random.Generator, count: int) -> np.ndarray:
    """Distance from each pixel to its Voronoi border (F2 - F1), wrapping on both axes."""
    py = rng.uniform(0, h, count)
    px = rng.uniform(0, w, count)
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float64)
    f1 = np.full((h, w), np.inf)
    f2 = np.full((h, w), np.inf)
    for y0, x0 in zip(py, px):
        d = np.hypot(wrap_dist(yy, y0, h), wrap_dist(xx, x0, w))
        f2 = np.where(d < f1, f1, np.minimum(f2, d))
        f1 = np.minimum(f1, d)
    return f2 - f1


def stamp(lum: np.ndarray, rng: np.random.Generator, count: int, radius: tuple[float, float],
          value: tuple[float, float], shadow: float = 0.0, region: np.ndarray | None = None) -> None:
    """Small pebbles/clods: soft ellipses (wrapping), each with an optional cast shade."""
    h, w = lum.shape
    for _ in range(count):
        y, x = rng.uniform(0, h), rng.uniform(0, w)
        if region is not None and region[int(y) % h, int(x) % w] < rng.random():
            continue
        r = rng.uniform(*radius)
        ry, rx = r * rng.uniform(0.7, 1.3), r * rng.uniform(0.7, 1.3)
        y0, y1 = int(y - 3 * r) - 2, int(y + 3 * r) + 3
        x0, x1 = int(x - 3 * r) - 2, int(x + 3 * r) + 3
        ys = np.arange(y0, y1) % h
        xs = np.arange(x0, x1) % w
        gy, gx = np.meshgrid(np.arange(y0, y1) - y, np.arange(x0, x1) - x, indexing="ij")
        if shadow:
            d = np.hypot((gy - r * 0.45) / ry, (gx - r * 0.45) / rx)
            patch = lum[np.ix_(ys, xs)]
            lum[np.ix_(ys, xs)] = patch - shadow * smooth(1.25, 0.6, d)
        d = np.hypot(gy / ry, gx / rx)
        mask = smooth(1.05, 0.7, d)
        v = rng.uniform(*value)
        patch = lum[np.ix_(ys, xs)]
        lum[np.ix_(ys, xs)] = patch * (1 - mask) + (v - 0.12 * gy / max(ry, 1)) * mask


# --- printing -----------------------------------------------------------------------------


def ramp(lum: np.ndarray, tint: np.ndarray | None = None) -> np.ndarray:
    lum = np.clip(lum, 0.0, 1.0)
    keys = np.array([k for k, _ in RAMP])
    cols = np.array([c for _, c in RAMP], np.float64)
    rgb = np.stack([np.interp(lum, keys, cols[:, i]) for i in range(3)], axis=-1)
    if tint is not None:
        rgb = rgb + tint
    return np.clip(rgb, 0, 255)


def print_plate(rgb: np.ndarray, colors: int, alpha: np.ndarray | None = None) -> Image.Image:
    """Dither onto `colors` palette entries (the print's grain). Alpha, if any, is cut to
    0/255 for alpha scissor; the transparent pixels keep the colour of the plate."""
    img = Image.fromarray((rgb + 0.5).astype(np.uint8))
    pal = img.quantize(colors=colors, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    out = img.quantize(palette=pal, dither=Image.Dither.FLOYDSTEINBERG).convert("RGB")
    if alpha is None:
        return out
    out = out.convert("RGBA")
    out.putalpha(Image.fromarray(np.where(alpha > 0.5, 255, 0).astype(np.uint8)))
    return out


# --- the earth along the ditch -----------------------------------------------------------


def street_earth() -> Image.Image:
    """Packed bare earth on the road side of the ditch (plan, 4.8 x 9.6 m, alpha cut).

    Lighter than the asphalt, dried to chalk in patches that have cracked into plates;
    dark where it is still wet. Rainwater has cut runnels across it, from the road down
    into the ditch, fanning out and darkening where they reach the bank - the long dark
    bands of the reference, laid crosswise. Grit and pebbles; and at the east edge the
    earth gives out in crumbs over the asphalt."""
    rng = np.random.default_rng(3151)
    w, h = int(EARTH_M[0] * EARTH_PX_M), int(EARTH_M[1] * EARTH_PX_M)
    u = np.arange(w)[None, :] / EARTH_PX_M  # metres from the bank
    v = np.arange(h)[:, None] / EARTH_PX_M
    big = fbm(h, w, rng, 40.0)
    mid = fbm(h, w, rng, 9.0, 3)
    fine = wrap_noise(h, w, rng, 1.2)
    lum = 0.55 + 0.11 * big + 0.06 * mid + 0.035 * fine

    # dried chalky plates with cracks between them, and wet dark ground between those
    dry = smooth(0.15, 0.75, big + 0.3 * mid)
    wet = smooth(-0.35, -0.95, big - 0.25 * mid)
    lum += 0.2 * dry - 0.2 * wet
    # the plates' borders, pushed about so they wander, and broken where the noise says
    # the ground has not split yet
    edges = cells(h, w, rng, 110)
    yy, xx = np.mgrid[0:h, 0:w]
    wy = (yy + 4.0 * wrap_noise(h, w, rng, 9.0)).astype(int) % h
    wx = (xx + 4.0 * wrap_noise(h, w, rng, 9.0)).astype(int) % w
    edges = edges[wy, wx] + 0.3 * wrap_noise(h, w, rng, 1.5)
    crack_w = 0.9 + 1.6 * smooth(-1, 1.2, wrap_noise(h, w, rng, 5.0))
    crack = smooth(crack_w, 0.0, edges) * smooth(0.2, 0.6, dry) * smooth(-1.1, -0.3, wrap_noise(h, w, rng, 14.0))
    lum -= 0.42 * crack

    # runnels from the road into the ditch: meandering, widening and darkening downhill
    for i in range(7):
        z0 = (i + rng.uniform(0.1, 0.9)) * EARTH_M[1] / 7
        slant = rng.uniform(-0.25, 0.25)
        phase = rng.uniform(0, 2 * np.pi)
        reach = rng.uniform(2.2, 4.4)
        centre = z0 + slant * u + 0.09 * np.sin(u * 2.3 + phase) + 0.04 * np.sin(u * 7.1 + 2 * phase)
        d = wrap_dist(np.broadcast_to(v, (h, w)), centre, EARTH_M[1])
        width = 0.025 + 0.11 * smooth(reach, 0.0, u) ** 2
        depth = smooth(reach, reach - 1.2, u)
        lum -= 0.34 * depth * smooth(width * 1.6, width * 0.3, d)
        # the silt the runnel leaves at its edges is paler
        lum += 0.08 * depth * smooth(width * 2.6, width * 1.7, d) * smooth(width * 1.2, width * 1.6, d)

    # damp ground along the lip of the bank, crumbling in
    lum -= 0.22 * smooth(0.45, 0.0, u + 0.08 * mid)
    lum -= 0.25 * smooth(0.06, 0.0, u + 0.02 * fine)

    stamp(lum, rng, 700, (0.7, 1.6), (0.38, 0.72), shadow=0.1)
    stamp(lum, rng, 110, (1.6, 3.2), (0.45, 0.8), shadow=0.16)

    # the east edge gives out: a ragged front around 3.6 m, crumbs beyond it
    front = 3.55 + 0.35 * wrap_noise(h, 1, rng, 60.0)[:, :1] + 0.12 * wrap_noise(h, 1, rng, 12.0)[:, :1]
    rough = 0.16 * fbm(h, w, rng, 8.0, 3)
    cover = smooth(0.1, -0.1, u - front + rough)
    crumbs = (fbm(h, w, rng, 3.0, 2) > 1.05 - 0.9 * smooth(1.1, 0.0, u - front)).astype(np.float64)
    alpha = np.maximum(cover, crumbs * smooth(front + 1.1, front, u))
    # crumbs are drier and paler than the ground they came off
    lum = np.where(cover < 0.5, lum + 0.08, lum)

    tint = np.zeros((h, w, 3))
    tint[..., 0] += 6 * dry - 4 * wet
    tint[..., 2] += 5 * wet
    return print_plate(ramp(lum, tint), 20, alpha)


# --- the ditch ----------------------------------------------------------------------------


def ditch_water() -> Image.Image:
    """The water in the ditch (plan, 0.625 x 9.6 m). It holds the sky: pale, brighter than
    the street around it, with long clouds drawn out along the ditch - and, against the
    kerb, the kerb's dark reflection. A scum line on both sides, leaves and a scrap of
    paper riding in it."""
    rng = np.random.default_rng(3152)
    w, h = int(WATER_M[0] * WATER_PX_M), int(WATER_M[1] * WATER_PX_M)
    u = np.arange(w)[None, :] / w
    sky = 0.84 + 0.05 * fbm(h, w, rng, 260.0, 2, sx=40.0)
    clouds = fbm(h, w, rng, 90.0, 3, sx=14.0)
    lum = sky + 0.1 * smooth(0.3, 1.2, clouds) - 0.06 * smooth(-0.4, -1.2, clouds)
    # slow ripples, drawn across the flow
    lum += 0.025 * wrap_noise(h, w, rng, 3.0, 18.0)
    # the kerb in the water (west, column 0) and the bank's darker earth (east)
    lum -= 0.5 * smooth(0.32, 0.08, u + 0.02 * wrap_noise(h, w, rng, 10.0))
    lum -= 0.22 * smooth(0.82, 0.97, u)
    # scum and silt held against both walls
    scum = smooth(0.4, 1.2, fbm(h, w, rng, 6.0, 3))
    lum -= 0.3 * scum * (smooth(0.07, 0.0, u) + smooth(0.93, 1.0, u))
    # leaves and a paper scrap
    stamp(lum, rng, 26, (1.5, 3.5), (0.18, 0.35))
    for _ in range(2):
        y, x = rng.uniform(0, h), rng.uniform(0.35, 0.7) * w
        ys = np.arange(int(y) - 10, int(y) + 10) % h
        xs = np.arange(int(x) - 7, int(x) + 7) % w
        lum[np.ix_(ys, xs)] = 0.98
    tint = np.zeros((h, w, 3))
    # warm at the top of the sky, a cooler lilac in the clouds' shade
    tint[..., 0] += 8 * smooth(0.0, 1.0, clouds)
    tint[..., 2] += 10 * smooth(0.0, -1.0, clouds)
    return print_plate(ramp(lum, tint), 16)


def ditch_wall() -> Image.Image:
    """The lining under the kerb, seen from the road (2.48 x 0.62 m, tiles sideways).
    Cast concrete, pitted, with rust-dark runs from the kerb joint; a band of green-black
    slime at the waterline and black wet below it."""
    rng = np.random.default_rng(3153)
    w, h = int(WALL_M[0] * WALL_PX_M), int(WALL_M[1] * WALL_PX_M)
    y = np.arange(h)[:, None] / WALL_PX_M  # metres below the kerb's foot
    lum = 0.6 + 0.07 * fbm(h, w, rng, 24.0) + 0.05 * wrap_noise(h, w, rng, 1.0)
    # runs from the top edge, longest where the noise says the joint leaks
    runs = smooth(0.2, 1.4, wrap_noise(1, w, rng, 1.0, 5.0))[0]
    length = 0.06 + 0.3 * runs
    lum -= 0.22 * runs[None, :] * smooth(length[None, :], 0.0, y)
    # pores
    stamp(lum, rng, 260, (0.6, 1.4), (0.3, 0.45))
    # the waterline: slime band, then wet
    line = WATERLINE_M + 0.012 * wrap_noise(1, w, rng, 1.0, 20.0)[0][None, :]
    band = smooth(line - 0.06, line - 0.01, y)
    lum = lum * (1 - 0.55 * band) - 0.08 * band
    tint = np.zeros((h, w, 3))
    tint[..., 1] += 9 * band * smooth(line + 0.03, line - 0.01, y)
    tint[..., 0] += 6 * runs[None, :] * smooth(length[None, :], 0.0, y)
    return print_plate(ramp(lum, tint), 16)


def ditch_grate() -> Image.Image:
    """Cast iron, a 0.2 m tile of slots across the ditch, worn bright on the bars."""
    rng = np.random.default_rng(3154)
    n = 64
    yy, xx = np.mgrid[0:n, 0:n] / n
    lum = 0.5 + 0.06 * wrap_noise(n, n, rng, 3.0)
    slot = (wrap_dist(yy, 0.25, 0.5) < 0.12) & (wrap_dist(xx, 0.5, 1.0) < 0.42)
    bar_top = (wrap_dist(yy, 0.0, 0.5) < 0.06)
    lum = np.where(bar_top, lum + 0.22, lum)
    lum = np.where(slot, 0.06, lum)
    return print_plate(ramp(lum), 8)


TEXTURES = {
    "street_earth.png": street_earth,
    "ditch_water.png": ditch_water,
    "ditch_wall.png": ditch_wall,
    "ditch_grate.png": ditch_grate,
}


def save(img: Image.Image, name: str) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / name
    img.save(path, optimize=True)
    (OUT_DIR / (name + ".import")).write_text(import_sidecar(f"{RES_DIR}/{name}"))
    print(f"{name:20s} {img.size[0]:5d} x {img.size[1]:<5d} {path.stat().st_size / 1024:7.1f} KiB")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("names", nargs="*", help="only these textures (file names)")
    args = parser.parse_args()
    for name, painter in TEXTURES.items():
        if not args.names or name in args.names:
            save(painter(), name)


if __name__ == "__main__":
    main()
