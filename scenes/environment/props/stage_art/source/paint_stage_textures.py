#!/usr/bin/env python3
"""Paints the textures of the stage pass over the walkway, street, courtyard and alley.

    python3 scenes/environment/props/stage_art/source/paint_stage_textures.py

Writes every PNG under `scenes/environment/props/stage_art/textures/` with its Godot
`.import` sidecar. Nothing is downloaded, traced, photographed or generated by an image
model: every mark is a plane, brush or line placed by the code below from a fixed seed
(3101-3199), so the same command on the same Pillow/NumPy versions repaints the same
files. The brush vocabulary is the classroom painter's, imported read-only, and the
yard's helpers (`planes`, `specks`, `make_tileable`) are imported read-only as well, so
the whole school is drawn by one hand. The colours are each location's own (README.md).

Coordinates. `Canvas` measures in metres with y up from the bottom edge. Plan textures
(floors, distance floors) are painted with the canvas top towards world -Z (north), which
is where a Godot PlaneMesh puts v = 0; walls are painted as seen from the walkway.
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import numpy as np
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
sys.path.insert(0, str(ROOT / "art" / "classroom"))
sys.path.insert(0, str(ROOT / "scenes" / "environment" / "props" / "playground_art" / "source"))

from paint_classroom_textures import Canvas, import_sidecar, jitter, rgb, smoothstep, value_noise  # noqa: E402
from paint_playground_textures import make_tileable, planes, specks  # noqa: E402

OUT_DIR = HERE.parent / "textures"
RES_DIR = "res://scenes/environment/props/stage_art/textures"

INK = (43, 38, 34)

# --- the walkway (corridor) ---------------------------------------------------------------
# A school walkway, not an office: chalky plaster over a deep green wainscot (the
# classroom's horizon line, carried outside), a terrazzo floor with brass strips.
PLASTER = (206, 198, 174)
PLASTER_LIGHT = (218, 211, 188)
PLASTER_DARK = (186, 176, 152)
PILASTER = (170, 160, 138)
DADO = (52, 94, 80)
DADO_LIGHT = (62, 108, 92)
DADO_DARK = (42, 80, 68)
TERRAZZO = (92, 56, 48)
TERRAZZO_LIGHT = (104, 64, 54)
TERRAZZO_DARK = (80, 48, 42)
BRASS = (150, 118, 70)

WALL_LEN = 16.0  # z from +7 (south, s = 0) to -9 (north, s = 16)
WALL_H = 3.1
FLOOR_W = 4.4


def dado_top(s: float) -> float:
    """The wainscot's top edge sinks along the walkway: 1.3 m at the stairs, 0.8 m at the
    yard door. Against a level trim line that reads as distance that is not there."""
    return 1.3 - 0.5 * (s / WALL_LEN)


def pilaster_positions() -> list[tuple[float, float]]:
    """Pilasters at a spacing that shrinks towards the far end (forced perspective).
    Skips the stretches the door, the glass, the extinguisher and the noticeboard cover."""
    covered = [(1.8, 3.8), (4.3, 5.7), (6.6, 7.3), (7.9, 10.1)]
    out: list[tuple[float, float]] = []
    s, gap, width = 0.6, 2.9, 0.34
    while s < WALL_LEN - 0.3:
        if not any(a - width < s < b + width for a, b in covered):
            out.append((s, width))
        s += gap
        gap = max(1.0, gap * 0.8)
        width = max(0.2, width * 0.9)
    return out


def corridor_wall() -> Image.Image:
    c = Canvas(WALL_LEN, WALL_H, 96.0, PLASTER, seed=3101)
    rng = c.rng
    planes(c, PLASTER_LIGHT, PLASTER_DARK, 90, (1.0, 2.6), (0.25, 0.5), angle=math.pi / 2, opacity=0.45)
    c.mottle(rgb(PLASTER_DARK), 2.5, 0.25)
    for s, w in pilaster_positions():
        lean = rng.normal(0, 0.03)
        c.paint(PILASTER, c.polygon_mask([(s, 0), (s + w, 0), (s + w + lean, WALL_H), (s + lean, WALL_H)], rough=0.3, cell_m=0.05), 0.85)
        c.ink_line([(s + w, 0.0), (s + w + lean, WALL_H)], width_m=0.03, wobble_m=0.01, opacity=0.7)
    # the wainscot, its top edge brushed rather than ruled
    pts = [(-0.1, 0.0)] + [(x, dado_top(x) + rng.normal(0, 0.012)) for x in np.linspace(-0.1, WALL_LEN + 0.1, 40)] + [(WALL_LEN + 0.1, 0.0)]
    c.paint(DADO, c.polygon_mask(pts, rough=0.25, cell_m=0.04), 1.0)
    strokes = []
    for _ in range(70):
        x = rng.uniform(0, WALL_LEN)
        top = dado_top(x) - 0.05
        strokes.append(([(x, rng.uniform(0.05, top * 0.6)), (x + rng.uniform(-0.05, 0.05), top)], rng.uniform(0.15, 0.4), {"bristles": 10, "dryness": 0.5, "wobble_m": 0.01}))
    c.brush(rgb(DADO_LIGHT), strokes[0::2], opacity=0.35)
    c.brush(rgb(DADO_DARK), strokes[1::2], opacity=0.35)
    c.ink_line([(x, dado_top(x)) for x in np.linspace(0.0, WALL_LEN, 12)], width_m=0.03, wobble_m=0.008, opacity=0.9, taper=False)
    # a fresher rectangle where something used to hang, and a tally at hand height
    c.paint(PLASTER_LIGHT, c.rect_mask(12.4, 1.45, 13.3, 2.15, rough=0.3, cell_m=0.05), 0.7)
    for k in range(6):
        x = 14.1 + k * 0.05
        c.chalk([(x, 1.42), (x + 0.01, 1.58)], 0.012, color=(232, 226, 210), opacity=0.7)
    c.chalk([(14.08, 1.46), (14.38, 1.55)], 0.012, color=(232, 226, 210), opacity=0.7)
    return c.image(12)


def corridor_floor() -> Image.Image:
    c = Canvas(FLOOR_W, WALL_LEN, 64.0, TERRAZZO, seed=3102)
    rng = c.rng
    planes(c, TERRAZZO_LIGHT, TERRAZZO_DARK, 60, (0.8, 2.0), (0.2, 0.5), angle=None, opacity=0.45)
    specks(c, rgb((150, 124, 104)), 0.03)
    specks(c, rgb((64, 40, 36)), 0.02)
    # A lane worn paler down the middle, where everyone walks.
    xs = np.linspace(0, FLOOR_W, c.w, dtype=np.float32)[None, :]
    lane = smoothstep(1.3, 0.3, np.abs(xs - FLOOR_W / 2) + (value_noise(c.w, c.h, 10, rng, 2) - 0.5) * 0.8)
    c.paint(TERRAZZO_LIGHT, np.broadcast_to(lane, (c.h, c.w)), 0.35)
    # Brass strips. The long ones converge towards the far end; the cross ones bunch up.
    centre = FLOOR_W / 2

    def x_at(f: float, y: float) -> float:
        return centre + (f - 0.5) * FLOOR_W * (1.0 - 0.38 * y / WALL_LEN)

    for f in (0.08, 0.5, 0.92):
        c.ink_line([(x_at(f, y), y) for y in np.linspace(0, WALL_LEN, 10)], width_m=0.035, wobble_m=0.01, color=BRASS, opacity=0.8, taper=False)
    y, gap = 0.4, 1.7
    while y < WALL_LEN:
        c.ink_line([(x_at(0.08, y), y), (x_at(0.92, y), y + rng.normal(0, 0.02))], width_m=0.03, wobble_m=0.01, color=BRASS, opacity=0.75, taper=False)
        y += gap
        gap = max(0.35, gap * 0.85)
    return c.image(12)


# --- distance floors ----------------------------------------------------------------------
# The camera looks down at ~53 degrees, so past any open edge it sees *below* the horizon.
# As in the yard, the sky is laid flat under the stage in bands by distance from the
# playable rectangle: a glow at the edge, then rose, mauve and dusty blue.
SKY_HIGH = (64, 74, 100)
SKY_MAUVE = (84, 76, 104)
SKY_BELT = (100, 80, 94)
SKY_GLOW = (104, 84, 86)


def distance_floor(size_m: float, centre: tuple[float, float], rect: tuple[float, float, float, float], seed: int, glow=SKY_GLOW, belt=SKY_BELT, bands=(4.0, 14.0, 30.0), px: int = 512) -> Image.Image:
    c = Canvas(size_m, size_m, px / size_m, SKY_HIGH, seed=seed)
    half = size_m / 2
    cx, cz = centre
    xs = np.linspace(cx - half, cx + half, c.w, dtype=np.float32)[None, :]
    zs = np.linspace(cz - half, cz + half, c.h, dtype=np.float32)[:, None]
    x0, x1, z0, z1 = rect
    dx = np.maximum(np.maximum(x0 - xs, xs - x1), 0.0)
    dz = np.maximum(np.maximum(z0 - zs, zs - z1), 0.0)
    d = np.sqrt(dx * dx + dz * dz) + (value_noise(c.w, c.h, 18.0, c.rng, 3) - 0.5) * 6.0
    c.paint(SKY_MAUVE, smoothstep(bands[2], bands[2] * 0.6, d), 1.0)
    c.paint(belt, smoothstep(bands[1], bands[1] * 0.55, d), 1.0)
    c.paint(glow, smoothstep(bands[0], bands[0] * 0.25, d), 1.0)
    rng = c.rng
    before = c.rgb.copy()
    clouds = []
    for _ in range(12):
        s, y = rng.uniform(0, size_m), rng.uniform(0, size_m)
        clouds.append(([(s, y), (s + rng.uniform(20, 50), y + rng.uniform(-2, 2))], rng.uniform(2.0, 5.0), {"bristles": 10, "dryness": 0.6, "wobble_m": 0.4}))
    c.brush(rgb((76, 86, 112)), clouds[0::2], opacity=0.5)
    c.brush(rgb((54, 64, 88)), clouds[1::2], opacity=0.45)
    far = smoothstep(bands[1], bands[2], d)[..., None]
    c.rgb = before * (1.0 - far) + c.rgb * far
    return c.image(9)


# --- the street ---------------------------------------------------------------------------
BONE = (214, 206, 186)


def dash_line() -> Image.Image:
    """The road's centre line (0.4 x 56 m strip, alpha): dashes of uneven length that lose
    the line halfway, start again a hand's width over, and give out before the stair."""
    c = Canvas(0.4, 56.0, 24.0, BONE, seed=3111, alpha=0.0)
    rng = c.rng
    y = 0.6
    while y < 52.0:
        length = rng.uniform(1.6, 2.6)
        off = 0.0 if y < 27.0 else 0.09
        if 24.5 < y < 27.5:
            y += 1.4
            continue
        c.paint_alpha(BONE, c.rect_mask(0.12 + off, y, 0.27 + off, y + length, rough=0.4, cell_m=0.03), 1.0)
        y += length + rng.uniform(1.2, 2.4) * (1.0 + y / 40.0)
    return c.image(3, alpha="cut")


def zebra() -> Image.Image:
    """A crossing (18.4 x 3 m, alpha): bars laid by hand, one missing, the last one short."""
    c = Canvas(18.4, 3.0, 24.0, BONE, seed=3112, alpha=0.0)
    rng = c.rng
    for k in range(15):
        if k == 9:
            continue
        s = 0.5 + k * 1.2 + rng.normal(0, 0.05)
        top = 2.85 if k < 14 else 1.6
        c.paint_alpha(BONE, c.polygon_mask([(s, 0.15 + rng.normal(0, 0.04)), (s + 0.55, 0.15), (s + 0.55 + rng.normal(0, 0.04), top), (s, top)], rough=0.45, cell_m=0.04), 1.0)
    return c.image(3, alpha="cut")


def window_tile() -> Image.Image:
    """Barred school windows (8 x 6.5 m tile, alpha) for the street's long school wall.
    Two to a row, two rows; one window in four sits a little lower than its neighbour."""
    c = Canvas(8.0, 6.5, 32.0, (58, 58, 78), seed=3113, alpha=0.0)
    rng = c.rng
    for row, y in enumerate((1.4, 4.6)):
        for col, s in enumerate((1.2, 5.0)):
            dy = -0.25 if (row, col) == (1, 1) else 0.0
            c.paint_alpha((58, 58, 78), c.rect_mask(s, y + dy, s + 2.2, y + 1.5 + dy, rough=0.3, cell_m=0.04), 1.0)
            c.paint_alpha((74, 74, 96), c.rect_mask(s + 0.15, y + 0.85 + dy, s + 1.0, y + 1.4 + dy, rough=0.3, cell_m=0.04), 0.8)
            for k in range(6):
                x = s + 0.2 + k * 0.36
                c.ink_line([(x, y - 0.05 + dy), (x + rng.normal(0, 0.01), y + 1.55 + dy)], width_m=0.035, wobble_m=0.01, alpha_canvas=True)
            c.ink_line([(s - 0.06, y + dy), (s + 2.26, y + dy)], width_m=0.08, wobble_m=0.01, color=(196, 188, 166), alpha_canvas=True, taper=False)
    return c.image(6, alpha="cut")


# --- the courtyard ------------------------------------------------------------------------
def hopscotch() -> Image.Image:
    """Chalk hopscotch (1.6 x 4.4 m, alpha): eight boxes, the fourth drawn twice, a little
    to the side of where it was first drawn."""
    c = Canvas(1.6, 4.4, 64.0, (226, 222, 210), seed=3121, alpha=0.0)
    chalk = (226, 222, 210)
    rows = [(0.2, 1), (0.75, 1), (1.3, 2), (1.85, 1), (2.4, 2), (2.95, 1), (3.5, 1)]
    for y, n in rows:
        w = 0.5
        for k in range(n):
            s = 0.8 - n * w / 2 + k * w
            box = [(s, y), (s + w, y), (s + w, y + 0.5), (s, y + 0.5), (s, y)]
            c.ink_line(box, width_m=0.035, wobble_m=0.01, color=chalk, alpha_canvas=True, taper=False, broken=0.4)
    again = [(0.62, 1.95), (1.12, 1.95), (1.12, 2.45), (0.62, 2.45), (0.62, 1.95)]
    c.ink_line(again, width_m=0.03, wobble_m=0.012, color=chalk, alpha_canvas=True, taper=False, broken=0.6, opacity=0.8)
    return c.image(3, alpha="cut")


# --- the alley ----------------------------------------------------------------------------
def streak_tile() -> Image.Image:
    """Near-white wall (4 x 4 m tile), tinted per material: long vertical drags and runs,
    the marks of rain on a wall that never gets the sun."""
    c = Canvas(4.0, 4.0, 96.0, (232, 230, 228), seed=3131)
    rng = c.rng
    planes(c, (246, 244, 242), (206, 202, 198), 40, (2.0, 4.0), (0.12, 0.3), angle=math.pi / 2, opacity=0.55, bristles=10)
    runs = []
    for _ in range(26):
        s = rng.uniform(0, 4.0)
        top = rng.uniform(2.5, 4.2)
        runs.append(([(s, top), (s + rng.normal(0, 0.03), top - rng.uniform(1.0, 2.6))], rng.uniform(0.02, 0.07), {"bristles": 5, "dryness": 0.5}))
    c.brush(rgb((176, 170, 166)), runs, opacity=0.6)
    make_tileable(c)
    return c.image(10)


def save(img: Image.Image, name: str) -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / name
    img.save(path, optimize=True)
    (OUT_DIR / (name + ".import")).write_text(import_sidecar(f"{RES_DIR}/{name}"))
    print(f"{name:26s} {img.size[0]:5d} x {img.size[1]:<5d} {path.stat().st_size / 1024:7.1f} KiB")


# Distance floors: (plane size, plane centre x/z, playable rectangle x0, x1, z0, z1).
# Kept in step with `build_stage_art.py`, which places the planes.
DISTANCE = {
    "corridor": (160.0, (20.0, -1.0), (-2.2, 2.2, -9.2, 7.6)),
    "street": (200.0, (0.0, -10.0), (-21.0, 22.0, -42.0, 20.0)),
    "residential": (200.0, (0.0, -10.0), (-23.5, 21.0, -40.0, 18.0)),
    "alley": (160.0, (0.0, -4.0), (-8.7, 4.2, -23.0, 15.0)),
}

TEXTURES = {
    "corridor_wall.png": corridor_wall,
    "corridor_floor.png": corridor_floor,
    "dash_line.png": dash_line,
    "zebra.png": zebra,
    "window_tile.png": window_tile,
    "hopscotch.png": hopscotch,
    "streak_tile.png": streak_tile,
    "distance_corridor.png": lambda: distance_floor(*DISTANCE["corridor"], seed=3141, bands=(6.0, 20.0, 44.0)),
    "distance_street.png": lambda: distance_floor(*DISTANCE["street"], seed=3142),
    "distance_residential.png": lambda: distance_floor(*DISTANCE["residential"], seed=3143, glow=(98, 88, 84), belt=(92, 84, 92)),
    "distance_alley.png": lambda: distance_floor(*DISTANCE["alley"], seed=3144, glow=(110, 86, 74), belt=(88, 76, 96), bands=(3.0, 10.0, 24.0)),
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("names", nargs="*", help="only these textures (file names)")
    args = parser.parse_args()
    total = 0
    for name, painter in TEXTURES.items():
        if args.names and name not in args.names:
            continue
        save(painter(), name)
        total += (OUT_DIR / name).stat().st_size
    print(f"total {total / 1024:.1f} KiB")


if __name__ == "__main__":
    main()
