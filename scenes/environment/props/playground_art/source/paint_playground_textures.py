# --- sky and distance ----------------------------------------------------------------------

SKY_SIZE = 240.0
SKY_PX = 512
# The yard's footprint as seen from above, including the school's roof line: distance to
# this rectangle is what the sky floor's bands are laid out by.
YARD_RECT = (-23.0, 23.0, -22.0, 20.0)  # x0, x1, z0, z1


def sky_floor() -> Image.Image:
    """The sky the camera sees past the yard's edge (240 x 240 m, plan view).

    The camera never looks above the horizon, so the sky is laid flat under the stage, in
    bands by distance from the yard: a pale glow along the edge, the rose band, mauve, and
    the dusty blue the background colour continues to infinity. Band edges are brushed,
    and a few long flat cloud strokes lie across the blue."""
    ppm = SKY_PX / SKY_SIZE
    c = Canvas(SKY_SIZE, SKY_SIZE, ppm, SKY_HIGH, seed=2115)
    half = SKY_SIZE / 2
    xs = np.linspace(-half, half, c.w, dtype=np.float32)[None, :]
    zs = np.linspace(-half, half, c.h, dtype=np.float32)[:, None]
    x0, x1, z0, z1 = YARD_RECT
    dx = np.maximum(np.maximum(x0 - xs, xs - x1), 0.0)
    dz = np.maximum(np.maximum(z0 - zs, zs - z1), 0.0)
    d = np.sqrt(dx * dx + dz * dz)
    noise = value_noise(c.w, c.h, 18.0, c.rng, 3)
    d = d + (noise - 0.5) * 7.0
    c.paint(SKY_MAUVE, smoothstep(30.0, 18.0, d), 1.0)
    c.paint(SKY_BELT, smoothstep(14.0, 8.0, d), 1.0)
    c.paint(SKY_GLOW, smoothstep(4.0, 1.0, d), 1.0)
    rng = c.rng
    before = c.rgb.copy()
    clouds = []
    for _ in range(14):
        s = rng.uniform(0, SKY_SIZE)
        y = rng.uniform(0, SKY_SIZE)
        clouds.append(([(s, y), (s + rng.uniform(25, 60), y + rng.uniform(-2, 2))], rng.uniform(2.5, 6.0), {"bristles": 10, "dryness": 0.6, "wobble_m": 0.5}))
    c.brush(rgb((116, 132, 160)), clouds[0::2], opacity=0.5)
    c.brush(rgb((88, 104, 134)), clouds[1::2], opacity=0.45)
    # Clouds only out in the blue, never in the warm bands along the yard's edge.
    far = smoothstep(16.0, 28.0, d)[..., None]
    c.rgb = before * (1.0 - far) + c.rgb * far
    return c.image(9)


def ground_row(kind: str, seed: int) -> Image.Image:
    """A ground-row silhouette (6 x 2.5 m, alpha): a flat cut-out of something far away -
    a block of flats, a water tower, a chimney and its shed, a pylon - hand-cut edges, no
    detail beyond a few notches. Coloured by the material, so the PNG is a mask."""
    c = Canvas(6.0, 2.5, 64.0, (255, 255, 255), seed=seed, alpha=0.0)
    rng = c.rng
    shapes: list[list[tuple[float, float]]] = []
    if kind == "flats":
        shapes.append([(0.2, 0.0), (0.2, 1.6), (1.4, 1.62), (1.4, 1.9), (3.1, 1.92), (3.1, 1.3), (4.4, 1.32), (4.4, 0.0)])
        shapes.append([(4.6, 0.0), (4.6, 0.7), (5.8, 0.72), (5.8, 0.0)])
    elif kind == "tower":
        shapes.append([(0.3, 0.0), (0.3, 0.5), (2.8, 0.52), (2.8, 0.0)])
        shapes.append([(3.6, 0.0), (3.7, 1.6), (3.85, 1.6), (3.95, 0.0)])
        shapes.append([(4.25, 0.0), (4.15, 1.6), (4.3, 1.6), (4.45, 0.0)])
        shapes.append([(3.45, 1.55), (3.5, 2.25), (4.65, 2.27), (4.7, 1.55)])
    elif kind == "chimney":
        shapes.append([(0.4, 0.0), (0.4, 0.75), (2.0, 1.05), (3.6, 0.75), (3.6, 0.0)])
        shapes.append([(4.3, 0.0), (4.42, 2.35), (4.66, 2.35), (4.8, 0.0)])
    else:  # pylon and a clump of trees
        shapes.append([(1.2, 0.0), (1.85, 2.3), (2.0, 2.3), (2.65, 0.0), (2.4, 0.0), (1.93, 1.7), (1.45, 0.0)])
        shapes.append([(1.4, 1.95), (2.45, 1.97), (2.45, 2.03), (1.4, 2.01)])
        shapes.append([(3.6, 0.0), (3.55, 0.5), (3.9, 0.9), (4.5, 1.0), (5.0, 0.8), (5.4, 0.45), (5.35, 0.0)])
    for pts in shapes:
        c.paint_alpha((255, 255, 255), c.polygon_mask(pts, rough=0.35, cell_m=0.04, blur_m=0.01), 1.0)
    if kind == "flats":
        for k in range(5):
            s = 0.5 + k * 0.7
            for y in (0.5, 1.0):
                if rng.random() < 0.6:
                    m = c.rect_mask(s, y, s + 0.22, y + 0.2, rough=0.3, cell_m=0.02)
                    c.a = c.a * (1.0 - m)
    return c.image(2, alpha="cut")


