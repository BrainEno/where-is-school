SLAB_M = 2.0
COURT_SLAB = (104, 104, 102)
YARD_SLAB = (94, 99, 109)


def tile_noise(w: int, h: int, cell_px: float, rng: np.random.Generator, stretch: tuple[float, float] = (1.0, 1.0)) -> np.ndarray:
    """Smooth noise in 0..1 that wraps exactly (white noise low-passed in Fourier space)."""
    white = rng.standard_normal((h, w))
    fy = np.fft.fftfreq(h)[:, None] * cell_px * stretch[1]
    fx = np.fft.fftfreq(w)[None, :] * cell_px * stretch[0]
    field = np.real(np.fft.ifft2(np.fft.fft2(white) * np.exp(-(fx * fx + fy * fy) * 9.0)))
    field = field / (field.std() + 1e-9)
    return np.clip(0.5 + field / 5.0, 0.0, 1.0).astype(np.float32)


def _stamp(value: np.ndarray, cx: float, cy: float, mask: np.ndarray, target: float, rim: np.ndarray | None = None) -> None:
    """Blends `mask` (odd square, centred on cx, cy) toward `target` in a wrapping field."""
    h, w = value.shape
    k = mask.shape[0] // 2
    rows = (int(cy) + np.arange(-k, k + 1)) % h
    cols = (int(cx) + np.arange(-k, k + 1)) % w
    patch = value[np.ix_(rows, cols)]
    patch = patch + (target - patch) * mask
    if rim is not None:
        patch = patch + rim
    value[np.ix_(rows, cols)] = patch


def _discs(value: np.ndarray, rng: np.random.Generator, count: int, radius: tuple[float, float], shade: tuple[float, float], rim: float = 0.0) -> None:
    """Stamps aggregate (stones broken open by wear) or pits into a wrapping value field."""
    yy, xx = np.mgrid[-6:7, -6:7].astype(np.float32)
    for _ in range(count):
        cx, cy = rng.uniform(0, value.shape[1]), rng.uniform(0, value.shape[0])
        r = rng.uniform(*radius)
        squash = rng.uniform(0.6, 1.0)
        angle = rng.uniform(0, math.pi)
        ca, sa = math.cos(angle), math.sin(angle)
        ox, oy = xx - (cx % 1.0), yy - (cy % 1.0)
        u = (ox * ca + oy * sa) / r
        v = (-ox * sa + oy * ca) / (r * squash)
        d = np.sqrt(u * u + v * v)
        ring = None
        if rim:
            ring = rim * np.clip(1.0 - np.abs(d - 1.25) * 3.0, 0.0, 1.0) * (oy < 0)
        _stamp(value, cx, cy, np.clip(1.6 - d * 1.6, 0.0, 1.0), rng.uniform(*shade), ring)


def _joints(value: np.ndarray, ppm: float, rng: np.random.Generator, core: float, width_px: float, chips: int, chip_shade: tuple[float, float]) -> None:
    """Sawn joints on every SLAB_M: a dark core, its edges broken out here and there."""
    h, w = value.shape
    step = int(round(SLAB_M * ppm))
    across = np.arange(w, dtype=np.float32)
    for axis in (0, 1):
        wobble = tile_noise(w, 2, 40.0, rng)[0]
        for k in range(0, w, step):
            d = np.abs(((across - k + w / 2) % w) - w / 2) + (wobble - 0.5) * 0.9
            line = np.clip(1.0 - (d - width_px / 2) / 0.9, 0.0, 1.0)
            if axis == 0:
                value[:] = value + (core - value) * line[None, :]
            else:
                value[:] = value + (core - value) * line[:, None]
    yy, xx = np.mgrid[-5:6, -5:6].astype(np.float32)
    for _ in range(chips):
        k = int(rng.integers(0, w // step)) * step
        along = rng.uniform(0, w)
        cx, cy = (k + rng.normal(0, 1.6), along) if rng.random() < 0.5 else (along, k + rng.normal(0, 1.6))
        r = rng.uniform(1.2, 3.6)
        m = np.clip(1.5 - np.sqrt(xx ** 2 + (yy * rng.uniform(0.5, 1.0)) ** 2) / r, 0.0, 1.0)
        _stamp(value, cx, cy, m, rng.uniform(*chip_shade))


def _hairlines(value: np.ndarray, rng: np.random.Generator, count: int, shade: float) -> None:
    h, w = value.shape
    for _ in range(count):
        x, y = rng.uniform(0, w), rng.uniform(0, h)
        a = rng.uniform(0, math.tau)
        for _ in range(int(rng.uniform(60, 180))):
            a += rng.normal(0, 0.35)
            x, y = x + math.cos(a), y + math.sin(a)
            j, i = int(y) % h, int(x) % w
            value[j, i] += (shade - value[j, i]) * 0.7


def court_tile() -> Image.Image:
    """Rough cement (4 m tile of one continuous pour): broom drag, open aggregate, pits.

    The court is the yard's roughest surface: coarse stone broken open by years of rubber
    soles, the fines worn out from between them, a broom drag across the pour. Round 21: the
    owner wanted one big court, not slabs, so it has no sawn joints and no slab-to-slab
    shifts in tone - its age is a few long cracks on their own decal (`court_cracks`).
    Neutral grey, so the white paint stays the brightest thing on it."""
    ppm = 192.0
    n = int(4.0 * ppm)
    rng = np.random.default_rng(2103)
    base = COURT_SLAB[0] / 255.0
    v = np.full((n, n), base, np.float32)
    v += (tile_noise(n, n, 150.0, rng) - 0.5) * 0.05    # broad stains (low: a 4 m repeat)
    v += (tile_noise(n, n, 34.0, rng) - 0.5) * 0.05     # trowel unevenness
    v += (tile_noise(n, n, 3.0, rng, stretch=(26.0, 1.0)) - 0.5) * 0.045  # the broom drag
    grain = rng.random((n, n)).astype(np.float32)
    v += np.where(grain > 0.975, 0.11, 0.0) - np.where(grain < 0.03, 0.09, 0.0)
    _discs(v, rng, 2600, (1.0, 2.6), (0.48, 0.62))   # pale quartz and limestone
    _discs(v, rng, 1500, (1.0, 2.4), (0.24, 0.32))   # dark basalt chips
    _discs(v, rng, 900, (0.7, 1.7), (0.16, 0.22), rim=0.05)  # pits where stones came out
    _hairlines(v, rng, 4, base - 0.1)
    c = Canvas(4.0, 4.0, ppm, COURT_SLAB, seed=2103)
    c.rgb = np.clip(np.stack([v, v, v * (COURT_SLAB[2] / COURT_SLAB[0])], axis=-1), 0.0, 1.0).astype(np.float32)
    return c.image(28)


def _crack_path(rng: np.random.Generator, start, heading: float, length: float, step: float = 0.22):
    """A meandering crack in world x, z: mostly straight, kinking every so often."""
    x, z = start
    pts = [(x, z)]
    a = heading
    for _ in range(max(2, int(length / step))):
        a += rng.normal(0.0, 0.16) + (rng.normal(0.0, 0.55) if rng.random() < 0.12 else 0.0)
        x, z = x + math.cos(a) * step, z + math.sin(a) * step
        if not (COURT_X0 + 0.2 < x < COURT_X1 - 0.2 and COURT_Z0 + 0.2 < z < COURT_Z1 - 0.2):
            break
        pts.append((x, z))
    return pts


# The court's cracks (world x, z start, heading in degrees, length m, branches). Few and
# long, as a single old pour cracks: shrinkage from the edge, one across the middle, the
# seam of the older yard coming up through the coat.
COURT_CRACKS = (
    ((-11.0, 3.6), 8.0, 5.2, 1),
    ((-6.4, -14.9), 74.0, 4.1, 1),
    ((11.0, -7.8), 186.0, 3.4, 0),
    ((-3.2, -4.6), 28.0, 6.4, 2),
    ((6.8, 10.9), 252.0, 2.8, 0),
    ((-9.4, -9.6), 128.0, 2.2, 0),
)


def court_cracks() -> Image.Image:
    """Aged cracks over the whole court (decal, alpha cut, x -11.12..11.12, z -15.12..11.12).

    One canvas for the whole pour so nothing repeats: a few long, kinked cracks with a
    branch or two, dark in the gap and a little darker at their broken lips, and the old
    yard seam (`SEAM`) reflected through the court as one more crack."""
    w_m, h_m = COURT_X1 - COURT_X0, COURT_Z1 - COURT_Z0
    c = Canvas(w_m, h_m, COURT_CRACK_PPM, INK, seed=2141, alpha=0.0)
    rng = np.random.default_rng(2141)

    def pt(x, z):
        return (x - COURT_X0, COURT_Z1 - z)

    def crack(path, width):
        line = [pt(x, z) for x, z in path]
        c.ink_line(line, width_m=width * 2.4, wobble_m=0.018, color=(86, 86, 84), opacity=1.0,
                   taper=True, broken=0.3, alpha_canvas=True)
        c.ink_line(line, width_m=width, wobble_m=0.01, color=(50, 50, 49), opacity=1.0,
                   taper=True, broken=0.12, alpha_canvas=True)

    for start, heading, length, branches in COURT_CRACKS:
        path = _crack_path(rng, start, math.radians(heading), length)
        crack(path, 0.022)
        for _ in range(branches):
            if len(path) < 6:
                break
            k = int(rng.integers(2, len(path) - 3))
            side = 1.0 if rng.random() < 0.5 else -1.0
            x0, z0 = path[k]
            x1, z1 = path[k + 1]
            base = math.atan2(z1 - z0, x1 - x0)
            crack(_crack_path(rng, path[k], base + side * rng.uniform(0.5, 1.0), rng.uniform(0.8, 2.2), 0.16), 0.014)
    # The yard seam, where the court crosses it, as a finer crack that follows its line.
    on_court = [(x, z) for x, z in SEAM if COURT_Z0 - 4.0 < z < COURT_Z1 + 4.0]
    dense = []
    for (xa, za), (xb, zb) in zip(on_court, on_court[1:]):
        n = max(2, int(math.hypot(xb - xa, zb - za) / 0.25))
        dense += [(xa + (xb - xa) * i / n, za + (zb - za) * i / n) for i in range(n)]
    # Only where the coat has given way: two stretches, wandering off the old line.
    drift = 0.0
    for z_lo, z_hi in ((-12.6, -6.8), (-1.5, 6.4)):
        stretch = []
        for x, z in dense:
            if z_lo < z < z_hi:
                drift = max(-0.25, min(0.25, drift + rng.normal(0, 0.05)))
                stretch.append((x + drift, z))
        crack(stretch, 0.016)
    return c.image(4, alpha="cut")


def yard_slab() -> Image.Image:
    """The plain concrete round the court (4 x 4 m tile): cooler, finer, steel-floated.

    On the yard it is drawn by the procedural slab shader (`yard_earth.gdshader`), which
    adds the passing cloud shadows; this tile is the same pour for the yard's own floor box,
    so what the HUD contrast test measures is what the shader paints."""
    ppm = 128.0
    n = int(4.0 * ppm)
    rng = np.random.default_rng(2131)
    tint = np.array(YARD_SLAB, np.float32) / YARD_SLAB[1]
    v = np.full((n, n), YARD_SLAB[1] / 255.0, np.float32)
    v += (tile_noise(n, n, 120.0, rng) - 0.5) * 0.06
    v += (tile_noise(n, n, 22.0, rng) - 0.5) * 0.03
    grain = rng.random((n, n)).astype(np.float32)
    v += np.where(grain > 0.985, 0.07, 0.0) - np.where(grain < 0.02, 0.06, 0.0)
    _discs(v, rng, 500, (0.7, 1.5), (0.27, 0.32))
    _hairlines(v, rng, 2, YARD_SLAB[1] / 255.0 - 0.07)
    _joints(v, ppm, rng, core=0.2, width_px=1.6, chips=50, chip_shade=(0.3, 0.45))
    c = Canvas(4.0, 4.0, ppm, YARD_SLAB, seed=2131)
    c.rgb = np.clip(v[..., None] * tint[None, None, :], 0.0, 1.0).astype(np.float32)
    return c.image(20)


def court_line() -> Image.Image:
    """A painted court line, 8 m of it (tiles along its length), 0.24 m of canvas across.

    About 0.11 m of brushed bone paint that wanders a little, thins and thickens, and was
    gone over twice - not a ruled stripe. Both ends sit on the centre of the strip so
    the tiles meet without a step."""
    c = Canvas(8.0, 0.24, 64.0, LINE, seed=2104, alpha=0.0)
    rng = c.rng
    knots = np.linspace(-0.3, 8.3, 10)
    pts = [(float(s), 0.12 + (0.0 if s < 0.2 or s > 7.8 else rng.uniform(-0.012, 0.012))) for s in knots]
    c.ink_line(pts, width_m=0.1, wobble_m=0.004, color=LINE, opacity=1.0, taper=False, broken=0.1, alpha_canvas=True)
    pts2 = [(x + rng.uniform(-0.05, 0.05), y + (0.0 if x < 0.2 or x > 7.8 else rng.uniform(-0.008, 0.008))) for x, y in pts]
    c.ink_line(pts2, width_m=0.08, wobble_m=0.004, color=LINE, opacity=1.0, taper=False, alpha_canvas=True)
    c.rgb[:] = rgb(LINE)
    planes(c, (244, 244, 239), (213, 213, 208), 30, (0.5, 1.6), (0.04, 0.08), angle=0.0, opacity=0.5, bristles=5)
    return c.image(6, alpha="cut")


def make_wrap_horizontal(c: Canvas) -> None:
    """Cross-fades the two ends of a strip so it tiles along u."""
    w = c.w
    shifted_rgb = np.roll(c.rgb, w // 2, axis=1)
    shifted_a = np.roll(c.a, w // 2, axis=1)
    ux = np.abs(np.linspace(-1.0, 1.0, w, dtype=np.float32))[None, :]
    keep = smoothstep(0.95, 0.6, ux)
    c.rgb = c.rgb * keep[..., None] + shifted_rgb * (1.0 - keep[..., None])
    c.a = np.maximum(c.a * keep, shifted_a * (1.0 - keep))


