def chain_link(width_m: float, height_m: float, seed: int, gap: tuple[float, float, float] | None = None) -> Image.Image:
    """A chain-link fence panel drawn in ink: a diamond mesh that wobbles, a top and bottom
    rail, a post at each end. `gap` = (centre s, half width, height) cuts the opening the
    yard's arrival text mentions, with the mesh peeled back at its edges."""
    ppm = 64.0
    c = Canvas(width_m, height_m, ppm, INK, seed=seed, alpha=0.0)
    rng = c.rng
    pitch = 0.3
    lines = []
    k = -height_m / pitch - 1
    while k * pitch < width_m + height_m:
        s0 = k * pitch
        lines.append(([(s0, 0.0), (s0 + height_m, height_m)]))
        lines.append(([(s0 + height_m, 0.0), (s0, height_m)]))
        k += 1
    for pts in lines:
        c.ink_line(pts, width_m=0.02, wobble_m=0.014, color=INK, opacity=1.0, taper=False, broken=0.08, alpha_canvas=True)
    if gap is not None:
        gs, ghw, gh = gap
        mask, draw = c.blank_mask()
        poly = [c.px(gs - ghw * 0.7, -0.1), c.px(gs + ghw, -0.1), c.px(gs + ghw * 0.8, gh * 0.75), c.px(gs + ghw * 0.2, gh), c.px(gs - ghw, gh * 0.85)]
        draw.polygon(poly, fill=255)
        hole = c.roughen(mask, 0.3, 0.05, 0.01)
        c.a = c.a * (1.0 - hole)
        # The cut ends, curled back: a few short hooked marks along the opening's edge.
        for t in np.linspace(0.05, 0.95, 9):
            s = gs - ghw + t * 2 * ghw * 0.95
            y = rng.uniform(0.1, gh * 0.8)
            c.ink_line([(s, y), (s + rng.uniform(-0.06, 0.06), y + 0.05), (s + rng.uniform(-0.1, 0.1), y + 0.02)], width_m=0.03, wobble_m=0.006, opacity=1.0, alpha_canvas=True)
    # Rails and posts.
    for y in (0.05, height_m - 0.05):
        c.ink_line([(-0.05, y), (width_m * 0.5, y + rng.uniform(-0.01, 0.01)), (width_m + 0.05, y)], width_m=0.045, wobble_m=0.008, opacity=1.0, taper=False, alpha_canvas=True)
    post_every = 3.0
    s = 0.04
    while s < width_m:
        if gap is None or abs(s - gap[0]) > gap[1] + 0.2:
            c.ink_line([(s, 0.0), (s + rng.uniform(-0.01, 0.01), height_m)], width_m=0.06, wobble_m=0.006, opacity=1.0, taper=False, alpha_canvas=True)
        s += post_every
    return c.image(4, alpha="cut")


