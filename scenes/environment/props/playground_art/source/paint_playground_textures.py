def make_wrap_horizontal(c: Canvas) -> None:
    """Cross-fades the two ends of a strip so it tiles along u."""
    w = c.w
    shifted_rgb = np.roll(c.rgb, w // 2, axis=1)
    shifted_a = np.roll(c.a, w // 2, axis=1)
    ux = np.abs(np.linspace(-1.0, 1.0, w, dtype=np.float32))[None, :]
    keep = smoothstep(0.95, 0.6, ux)
    c.rgb = c.rgb * keep[..., None] + shifted_rgb * (1.0 - keep[..., None])
    c.a = np.maximum(c.a * keep, shifted_a * (1.0 - keep))


