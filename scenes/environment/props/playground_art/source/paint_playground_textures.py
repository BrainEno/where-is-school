#!/usr/bin/env python3
"""Paints the schoolyard's hand-made textures.

    python3 scenes/environment/props/playground_art/source/paint_playground_textures.py

Writes every PNG under `scenes/environment/props/playground_art/textures/` together with
its Godot `.import` sidecar. Nothing here is downloaded, traced or generated by a model:
every mark is a brush, plane or line placed by the code below from a fixed seed, so the
same command on the same Pillow/NumPy versions repaints the same files.

The brush vocabulary (planes with roughened edges, dry brush, wobbling ink, chalk) is the
classroom's painter, imported read-only from `art/classroom/paint_classroom_textures.py`
so the two locations are drawn by the same hand. The *colours* are not shared: the yard
has its own local palette (README.md next to this folder), as the art bible asks.

Coordinates. Ground and sky textures are painted in plan: `s` is world x minus the left
edge of the texture, and the canvas's `y` is the texture's top edge in world z minus z, so
the numbers below can be checked against `playground.tscn` directly. The materials map
them with world triplanar UVs (u = x * scale + offset, v = z * scale + offset).
"""

