def make_tileable(c: Canvas) -> None:
    """Cross-fades the canvas with a copy shifted by half a tile, so it wraps."""
    h, w = c.h, c.w
    shifted = np.roll(np.roll(c.rgb, h // 2, axis=0), w // 2, axis=1)
    ux = np.abs(np.linspace(-1.0, 1.0, w, dtype=np.float32))
    uy = np.abs(np.linspace(-1.0, 1.0, h, dtype=np.float32))
    edge = np.maximum(ux[None, :], uy[:, None])
    keep = smoothstep(0.95, 0.55, edge)[..., None]
    c.rgb = c.rgb * keep + shifted * (1.0 - keep)


def planes(c: Canvas, light, dark, count: int, length: tuple[float, float], width: tuple[float, float], angle: float | None, opacity: float, bristles: int = 14) -> None:
    """Broad brush planes in two close values: a surface laid on by hand."""
    rng = c.rng
    lights, darks = [], []
    for _ in range(count):
        s = rng.uniform(-0.5, c.width_m + 0.5)
        y = rng.uniform(-0.5, c.height_m + 0.5)
        a = angle if angle is not None else rng.uniform(0, math.pi)
        a += rng.normal(0, 0.12)
        l = rng.uniform(*length)
        pts = [(s, y), (s + math.cos(a) * l, y + math.sin(a) * l)]
        entry = (pts, rng.uniform(*width), {"bristles": bristles, "dryness": 0.55, "wobble_m": 0.02})
        (lights if rng.random() < 0.5 else darks).append(entry)
    c.brush(jitter(light, rng, 0.02), lights, opacity=opacity)
    c.brush(jitter(dark, rng, 0.02), darks, opacity=opacity)


def specks(c: Canvas, color, density: float, size_px: int = 1, opacity: float = 0.6) -> None:
    """Aggregate in concrete: a sprinkling of single pixels, not noise everywhere."""
    mask = (c.rng.random((c.h, c.w)) < density).astype(np.float32)
    if size_px > 1:
        img = Image.fromarray((mask * 255).astype(np.uint8)).resize((c.w, c.h))
        mask = np.asarray(img, np.float32) / 255.0
    c.paint(color, mask, opacity)


