def rota_sheet() -> Image.Image:
    """The duty sheet taped in the shed window (0.9 x 0.5 m): nine ruled rows, scribbled
    entries that cannot be read in any language, the last two rows the same shape twice,
    rain having run two rows together, and tape at the corners."""
    c = Canvas(0.9, 0.5, 320.0, (232, 226, 206), seed=2110)
    rng = c.rng
    rows = 9
    top, bottom = 0.45, 0.04
    pitch = (top - bottom) / rows
    for r in range(rows + 1):
        y = top - r * pitch
        c.ink_line([(0.04, y), (0.86, y + rng.uniform(-0.002, 0.002))], width_m=0.002, wobble_m=0.001, color=(120, 112, 100), taper=False)
    c.ink_line([(0.22, top), (0.22, bottom)], width_m=0.002, wobble_m=0.001, color=(120, 112, 100), taper=False)
    last = None
    for r in range(rows):
        y = top - (r + 0.5) * pitch
        if r == rows - 1 and last is not None:
            shape = last  # the same day written twice
        else:
            shape = [(rng.uniform(0.0, 0.04), rng.uniform(-0.012, 0.012)) for _ in range(6)]
        last = shape
        pts = [(0.06 + i * 0.022 + dx, y + dy) for i, (dx, dy) in enumerate(shape)]
        c.ink_line(pts, width_m=0.004, wobble_m=0.002, color=(52, 56, 84))
        s = 0.26
        while s < rng.uniform(0.55, 0.8):
            c.ink_line([(s, y - 0.008), (s + 0.02, y + 0.01), (s + 0.04, y - 0.006)], width_m=0.003, wobble_m=0.002, color=(52, 56, 84))
            s += rng.uniform(0.05, 0.08)
    # Two rows run together where the rain got in.
    blot = c.rect_mask(0.24, top - 6.2 * pitch, 0.7, top - 4.8 * pitch, rough=0.5, cell_m=0.02, blur_m=0.01)
    c.paint((150, 150, 168), blot, 0.45)
    for s0, y0 in ((0.0, 0.42), (0.78, 0.42), (0.0, 0.0), (0.78, 0.0)):
        tape = c.rect_mask(s0, y0, s0 + 0.12, y0 + 0.08, rough=0.2, cell_m=0.01)
        c.paint((214, 204, 170), tape, 0.6)
    return c.image(16)


